my_list = ["Ali", "Nasim", "Aram", "Mehran", "Sepideh", "Bahar"]

count = 0
total_length = 0

for i in my_list:
    total_length = total_length + len(i)
    count = count + 1
    print(count, i, len(i))

print("Total length:", total_length)

               





